// กฎรูปแบบข้อมูลของการสมัครสมาชิกและตั้งรหัสผ่าน (TOR ข้อ 1 และ 3) ใช้ร่วมกันทุกหน้า เพื่อให้กฎตรงกันทุกที่

// อีเมล: มี @ และมีจุดในชื่อโดเมน เช่น name@company.co.th
export const EMAIL_REGEX = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

// รหัสผ่าน: อย่างน้อย 8 ตัว มีทั้งตัวอักษรอังกฤษและตัวเลข
export const PASSWORD_REGEX = /^(?=.*[A-Za-z])(?=.*\d).{8,}$/;

// Username: 3-20 ตัว ใช้ได้เฉพาะตัวอักษรอังกฤษ ตัวเลข _ และ -
export const USERNAME_REGEX = /^[a-zA-Z0-9_-]{3,20}$/;
